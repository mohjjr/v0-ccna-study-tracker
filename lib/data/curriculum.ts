// Helper function to get all lessons in a flat array
export function getAllLessons(): Lesson[] {
  return CURRICULUM.flatMap(module => module.lessons)
}

// Get lesson by ID
export function getLessonById(id: string): Lesson | undefined {
  return getAllLessons().find(lesson => lesson.id === id)
}

// Get module by ID
export function getModuleById(id: string): Module | undefined {
  return CURRICULUM.find(module => module.id === id)
}

// Get lessons by domain
export function getLessonsByDomain(domain: CCNADomain): Lesson[] {
  return getAllLessons().filter(lesson => lesson.domain === domain)
}

// Calculate total estimated study time
export function getTotalEstimatedTime(): number {
  return getAllLessons().reduce((total, lesson) => total + lesson.duration, 0)
}

// Get total lesson count
export function getTotalLessonCount(): number {
  return getAllLessons().length
}

// Get total lab count
export function getTotalLabCount(): number {
  return getAllLessons().filter(lesson => lesson.hasLab).length
}
